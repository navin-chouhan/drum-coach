// Copies the coach's prompts (server/prompts/*.md, the one source) into a TS module the iPad's API-key fallback reads:
// src/features/coach/direct/prompts.gen.ts. Run it after changing a prompt: `npm run gen:prompts` (in apps/mobile).
// prompts.test.ts fails when the module and the .md files differ, so a stale copy can't ship.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const app = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(app, '..', '..', 'server', 'prompts');
const out = join(app, 'src', 'features', 'coach', 'direct', 'prompts.gen.ts');

const names = readdirSync(dir).filter(f => f.endsWith('.md')).sort();
const body = names.map(f => `  ${JSON.stringify(f.replace(/\.md$/, ''))}: ${JSON.stringify(readFileSync(join(dir, f), 'utf8'))},`).join('\n');
writeFileSync(out, `// Generated by scripts/gen-coach-prompts.mjs from server/prompts/*.md. Do not edit: change the .md and run npm run gen:prompts.
export const PROMPTS = {
${body}
} as const;
export type PromptName = keyof typeof PROMPTS;
`);
console.log(`wrote ${names.length} prompts to ${out}`);
